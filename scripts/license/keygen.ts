/**
 * Vendor tool for the desktop licences (never shipped in the .exe).
 *
 *   npm run license:init                                  → creates your key pair (once)
 *   npm run license:create -- ABCD-EFGH-JKMN-PQRS "Client" → prints the activation key of a PC
 *
 * The PRIVATE key is written to license-keys/private.pem (excluded from git): keep a backup in
 * a safe place. Losing it means you can no longer create keys for the installed versions;
 * if someone gets it, they can create keys themselves.
 */
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { normalizeMachineCode, signLicense, verifyLicense } from '../../src/license/license.ts';

const ROOT = process.cwd();
const KEY_DIR = path.join(ROOT, 'license-keys');
const PRIVATE_FILE = path.join(KEY_DIR, 'private.pem');
const PUBLIC_TS = path.join(ROOT, 'src', 'license', 'publicKey.ts');

function init() {
  if (fs.existsSync(PRIVATE_FILE)) {
    console.error(`Une clé privée existe déjà (${PRIVATE_FILE}). Rien n'a été modifié.`);
    console.error('Supprimer cette clé rendrait invalides toutes les clés déjà distribuées.');
    process.exit(1);
  }
  const { privateKey, publicKey } = crypto.generateKeyPairSync('ed25519');
  fs.mkdirSync(KEY_DIR, { recursive: true });
  fs.writeFileSync(PRIVATE_FILE, privateKey.export({ type: 'pkcs8', format: 'pem' }).toString(), { mode: 0o600 });
  const pub = publicKey.export({ type: 'spki', format: 'pem' }).toString().trim();
  fs.writeFileSync(path.join(KEY_DIR, 'public.pem'), pub + '\n');
  fs.writeFileSync(
    PUBLIC_TS,
    `/** Public key checking the activation keys (generated by "npm run license:init"). */\nexport const LICENSE_PUBLIC_KEY_PEM = \`${pub}\n\`;\n`
  );
  console.log('Paire de clés créée.');
  console.log(`  Clé privée : ${PRIVATE_FILE}  ← à sauvegarder en lieu sûr, à ne jamais partager`);
  console.log(`  Clé publique intégrée à l'application : ${PUBLIC_TS}`);
}

function create(machine: string | undefined, customer: string | undefined) {
  if (!machine || !customer) {
    console.error('Usage : npm run license:create -- <CODE-MACHINE> "<Nom du client>"');
    process.exit(1);
  }
  if (!fs.existsSync(PRIVATE_FILE)) {
    console.error('Aucune clé privée : lancez d’abord « npm run license:init ».');
    process.exit(1);
  }
  const code = normalizeMachineCode(machine);
  if (!/^[0-9A-Z]{4}(-[0-9A-Z]{4}){3}$/.test(code)) {
    console.error(`Code machine invalide : « ${machine} » (attendu : 16 caractères, ex. ABCD-EFGH-JKMN-PQRS).`);
    process.exit(1);
  }
  const privatePem = fs.readFileSync(PRIVATE_FILE, 'utf8');
  const key = signLicense({ m: code, c: customer.trim(), d: new Date().toISOString().slice(0, 10) }, privatePem);
  // Self-check with the public key of the application
  const publicPem = fs.readFileSync(path.join(KEY_DIR, 'public.pem'), 'utf8');
  const check = verifyLicense(key, code, publicPem);
  if (!check.ok) {
    console.error(`La clé produite ne se vérifie pas : ${check.error}`);
    process.exit(1);
  }
  console.log(`Client : ${customer.trim()}`);
  console.log(`Code machine : ${code}`);
  console.log('Clé d’activation (à envoyer au client) :\n');
  console.log(key);
}

const [cmd, ...args] = process.argv.slice(2);
if (cmd === 'init') init();
else if (cmd === 'create') create(args[0], args.slice(1).join(' '));
else {
  console.log('Commandes : init | create <CODE-MACHINE> "<Nom du client>"');
  process.exit(1);
}
